import assert from "node:assert/strict";
import fs from "node:fs";
import { saudiLocationOptions as lookup } from "../features/saudi-locations.js";
const data = JSON.parse(fs.readFileSync(new URL("../features/saudi-locations-data/locations.json", import.meta.url)));
assert.equal(lookup().items.length, 13);
const regions = new Set(data.regions.map(row => row.region_id));
const cities = new Map(data.cities.map(row => [row.city_id, row.region_id]));
for (const row of data.cities) assert(regions.has(row.region_id));
for (const row of data.districts) assert.equal(cities.get(row.city_id), row.region_id);
const riyadh = lookup({ kind: "cities", region: "الرياض" }).items;
assert(riyadh.some(row => row.name_ar === "الرياض"));
assert(!riyadh.some(row => row.name_ar === "جدة"));
assert.deepEqual(lookup({ kind: "cities", region: "Riyadh" }), lookup({ kind: "cities", region: "منطقة الرِّياض" }));
assert.deepEqual(lookup({ kind: "cities", region: "Makkan" }), lookup({ kind: "cities", region: "مكة المكرمة" }));
const districts = lookup({ kind: "districts", region: "الرياض", city: "الرياض" }).items;
assert(districts.some(row => row.name_ar.includes("حطين")));
assert.equal(lookup({ kind: "districts", region: "مكة المكرمة", city: "الرياض" }).required_parent, "city");
assert.equal(lookup({ kind: "cities", region: "غير موجود" }).required_parent, "province");
assert.equal(lookup({ kind: "districts", region: "الرياض" }).required_parent, "city");
assert.throws(() => lookup({ kind: "invalid" }), /INVALID_ADDRESS_LOOKUP_KIND/);
console.log(`Passed ${data.cities.length} city/${data.districts.length} district parent links, Saudi aliases, cross-region isolation, and incomplete parents.`);
